"""The declared runtime floors are the versions the generated modules were built for.

protoc writes into every ``*_pb2.py`` a ``ValidateProtobufRuntimeVersion`` call with
the protobuf it generated the module with, and the protobuf runtime refuses to load
gencode newer than itself. Every ``*_pb2_grpc.py`` likewise raises at import when
``grpc.__version__`` is older than its ``GRPC_GENERATED_VERSION``. So the floors in
``pyproject.toml`` must be at least those versions: a lower floor lets pip accept an
install whose first import fails, while a higher one only asks for a runtime that
loads older gencode. Both sides are read from the installed distribution
(its metadata and the modules it ships), so the test judges what a user gets.
"""

from __future__ import annotations

import re
from importlib import metadata
from pathlib import Path

PACKAGE_ROOT = Path(__file__).resolve().parents[1]

_PROTOBUF_GENCODE = re.compile(
    r"ValidateProtobufRuntimeVersion\(\s*_runtime_version\.Domain\.PUBLIC,"
    r"\s*(\d+),\s*(\d+),\s*(\d+),"
)
_GRPC_GENCODE = re.compile(r"^GRPC_GENERATED_VERSION = '(\d+(?:\.\d+)*)'$", re.MULTILINE)


def _version(text: str) -> tuple[int, ...]:
    return tuple(int(part) for part in text.split("."))


def _dotted(version: tuple[int, ...]) -> str:
    return ".".join(str(part) for part in version)


def _declared_floor(dist: metadata.Distribution, name: str) -> tuple[int, ...]:
    """The ``>=`` version ``name`` carries in the distribution's Requires-Dist."""
    floor = re.compile(rf"^{re.escape(name)}(?![\w.-])\s*(?:[^;,]*,\s*)*>=\s*(\d+(?:\.\d+)*)")
    found = [match.group(1) for req in dist.requires or () if (match := floor.match(req))]
    assert len(found) == 1, f"one >= floor for {name} expected in {dist.requires}"
    return _version(found[0])


def _shipped_modules(dist: metadata.Distribution, suffix: str) -> dict[str, str]:
    """Text of the generated modules ending in ``suffix``, as the distribution ships them."""
    files = [
        Path(dist.locate_file(path))
        for path in dist.files or ()
        if path.parent.name == "generated" and path.name.endswith(suffix)
    ]
    if not files:
        # An editable install lists no package files; setup.py generated the stubs
        # into the source tree.
        files = sorted((PACKAGE_ROOT / "smg_grpc_proto" / "generated").glob(f"*{suffix}"))
    assert files, f"no generated *{suffix} modules found: build or install the package first"
    return {path.name: path.read_text() for path in files}


def test_protobuf_floor_is_the_gencode_version():
    dist = metadata.distribution("smg-grpc-proto")
    floor = _declared_floor(dist, "protobuf")
    for name, text in _shipped_modules(dist, "_pb2.py").items():
        match = _PROTOBUF_GENCODE.search(text)
        assert match, f"{name} carries no ValidateProtobufRuntimeVersion call"
        gencode = tuple(int(part) for part in match.groups())
        assert floor >= gencode, (
            f"{name} was generated for protobuf {_dotted(gencode)} but the package declares "
            f"protobuf>={_dotted(floor)}: a runtime older than the gencode refuses the import, "
            "so the floor must be at least the generator's protobuf version"
        )


def test_grpcio_floor_is_the_generated_version():
    dist = metadata.distribution("smg-grpc-proto")
    floor = _declared_floor(dist, "grpcio")
    for name, text in _shipped_modules(dist, "_pb2_grpc.py").items():
        match = _GRPC_GENCODE.search(text)
        assert match, f"{name} carries no GRPC_GENERATED_VERSION"
        generated = _version(match.group(1))
        assert floor >= generated, (
            f"{name} was generated by grpcio-tools {match.group(1)} but the package declares "
            f"grpcio>={_dotted(floor)}: the module raises on an older grpcio, so the floor "
            "must be at least the generator's version"
        )
