//! Heterogeneous context windows over real gateway -> tonic worker calls.
//! The tokenizer is a real, local Hugging Face WordLevel pipeline; captured
//! Generate requests verify the exact token count and the chosen workers.

#[path = "common/mod.rs"]
mod common;

use std::{path::PathBuf, sync::Arc, time::Duration};

use axum::http::StatusCode;
use llm_tokenizer::{traits::Tokenizer, HuggingFaceTokenizer, TokenizerRegistry};
use openai_protocol::{
    completion::CompletionRequest,
    model_card::ModelCard,
    worker::{HealthCheckConfig, WorkerStatus},
};
use smg::{
    config::{RouterConfig, RoutingMode},
    middleware::TenantRequestMeta,
    routers::{RouterFactory, RouterTrait},
    tenant::TenantKey,
    worker::{BasicWorkerBuilder, ConnectionMode, RuntimeType, Worker, WorkerType},
};
use tokio::{net::TcpListener, task::JoinHandle};

const MODEL: &str = "heterogeneous-context";

/// A real tonic listener and its worker-advertised window, with per-RPC capture.
struct Engine {
    worker: Arc<dyn Worker>,
    capture: PathBuf,
    task: JoinHandle<()>,
}

impl Drop for Engine {
    fn drop(&mut self) {
        self.task.abort();
    }
}

impl Engine {
    /// Start a mock whose server info agrees with its model card. Unknown
    /// means discovery supplied no window, not that the engine has zero room.
    #[expect(
        clippy::unwrap_used,
        clippy::disallowed_methods,
        reason = "local test listener; task is aborted on drop"
    )]
    async fn start(
        dir: &std::path::Path,
        name: &str,
        role: WorkerType,
        window: Option<u32>,
        protocol: &str,
    ) -> Self {
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let capture = dir.join(format!("{name}.jsonl"));
        let cfg = Arc::new(mock_worker::config::Config {
            context_length: window.unwrap_or(64),
            model_id: MODEL.into(),
            tokenizer_path: MODEL.into(),
            grpc_base_port: port,
            grpc_count: 1,
            http_count: 0,
            admin_port: None,
            gen_delay: Duration::ZERO,
            output_tokens: 1,
            replay: mock_worker::config::ReplayConfig {
                capture: Some(capture.clone()),
            },
            ..Default::default()
        });
        let task = tokio::spawn(mock_worker::grpc::serve_with_listener(cfg, listener));
        let mut card = ModelCard::new(MODEL);
        if let Some(window) = window {
            card = card.with_context_length(window);
        }
        let worker = Arc::new(
            BasicWorkerBuilder::new(format!("grpc://127.0.0.1:{port}"))
                .worker_type(role)
                .connection_mode(ConnectionMode::Grpc)
                .runtime_type(RuntimeType::TokenSpeed)
                .model(card)
                .label("pairing_protocol", protocol)
                .health_config(HealthCheckConfig {
                    disable_health_check: true,
                    ..Default::default()
                })
                .build(),
        );
        Self {
            worker,
            capture,
            task,
        }
    }

    /// Read the mock's synchronous record of every Generate received.
    #[expect(clippy::unwrap_used, reason = "capture is generated by the test mock")]
    fn calls(&self) -> Vec<serde_json::Value> {
        std::fs::read_to_string(&self.capture)
            .unwrap_or_default()
            .lines()
            .map(|line| serde_json::from_str(line).unwrap())
            .collect()
    }
}

/// Build a GPU-free router with the same tokenizer pipeline used in production.
/// Round robin makes the baseline's small-worker refusals deterministic.
#[expect(clippy::unwrap_used, reason = "fixture construction must succeed")]
async fn router(dir: &std::path::Path, engines: &[&Engine], pd: bool) -> Box<dyn RouterTrait> {
    let path = dir.join("tokenizer.json");
    let mut vocab = serde_json::Map::new();
    vocab.insert("[UNK]".into(), 0.into());
    vocab.insert("Hello".into(), 1.into());
    for id in 2..=100 {
        vocab.insert(format!("token{id}"), id.into());
    }
    std::fs::write(
        &path,
        serde_json::to_vec(&serde_json::json!({
            "version":"1.0", "truncation":null, "padding":null,
            "added_tokens":[], "normalizer":null,
            "pre_tokenizer":{"type":"WhitespaceSplit"},
            "post_processor":null, "decoder":null,
            "model":{"type":"WordLevel", "vocab":vocab, "unk_token":"[UNK]"}
        }))
        .unwrap(),
    )
    .unwrap();
    let tokenizer: Arc<dyn Tokenizer> =
        Arc::new(HuggingFaceTokenizer::from_file(path.to_str().unwrap()).unwrap());
    assert_eq!(
        tokenizer
            .encode(&"Hello ".repeat(24), true)
            .unwrap()
            .token_ids()
            .len(),
        24
    );
    let tokenizers = Arc::new(TokenizerRegistry::new());
    tokenizers
        .load("local", MODEL, "test", || async move { Ok(tokenizer) })
        .await
        .unwrap();
    let mode = if pd {
        RoutingMode::PrefillDecode {
            prefill_urls: vec![],
            decode_urls: vec![],
            prefill_policy: None,
            decode_policy: None,
        }
    } else {
        RoutingMode::Regular {
            worker_urls: vec![],
        }
    };
    let mut config = RouterConfig::builder()
        .mode(mode)
        .grpc_connection()
        .round_robin_policy()
        .host("127.0.0.1")
        .port(0)
        .build_unchecked();
    config.health_check.disable_health_check = true;
    let context = common::create_test_context_with_tokenizer_registry(config, tokenizers).await;
    for engine in engines {
        context
            .worker_registry
            .register(Arc::clone(&engine.worker))
            .unwrap();
    }
    RouterFactory::create_router(&context).await.unwrap()
}

/// Send precisely `tokens` token IDs via normal completion preparation.
#[expect(clippy::unwrap_used, reason = "fixture request and response")]
async fn request(router: &dyn RouterTrait, tokens: usize) -> (StatusCode, serde_json::Value) {
    let request: CompletionRequest = serde_json::from_value(serde_json::json!({
        "model":MODEL, "prompt":"Hello ".repeat(tokens), "max_tokens":1
    }))
    .unwrap();
    send(router, request).await
}

/// Exercise arbitrary completion shapes through the same bounded gateway call.
#[expect(clippy::unwrap_used, reason = "fixture response")]
async fn send(
    router: &dyn RouterTrait,
    request: CompletionRequest,
) -> (StatusCode, serde_json::Value) {
    let response = tokio::time::timeout(
        Duration::from_secs(10),
        router.route_completion(
            None,
            &TenantRequestMeta::new(TenantKey::new("context-routing")),
            request,
            MODEL,
        ),
    )
    .await
    .unwrap();
    let status = response.status();
    let body = axum::body::to_bytes(response.into_body(), 1 << 20)
        .await
        .unwrap();
    (status, serde_json::from_slice(&body).unwrap())
}

/// A mixed pool must succeed without sending a long input to the small engine
/// or spending a retry; a short input must still use both workers.
#[tokio::test]
#[expect(clippy::print_stderr, reason = "reproducible A/B diagnostics")]
async fn regular_routes_by_exact_context_without_retries() {
    let dir = tempfile::tempdir().unwrap();
    let small = Engine::start(dir.path(), "small", WorkerType::Regular, Some(16), "a").await;
    let large = Engine::start(dir.path(), "large", WorkerType::Regular, Some(64), "a").await;
    let router = router(dir.path(), &[&small, &large], false).await;
    let mut statuses = vec![];
    for _ in 0..8 {
        statuses.push(request(router.as_ref(), 24).await.0);
    }
    let long_counts = [small.calls().len(), large.calls().len()];
    eprintln!("regular long: statuses={statuses:?}, Generate={long_counts:?}");
    for call in large.calls() {
        assert_eq!(call["input_ids"].as_array().unwrap().len(), 24);
    }
    for _ in 0..8 {
        assert_eq!(request(router.as_ref(), 8).await.0, StatusCode::OK);
    }
    let short_counts = [
        small.calls().len() - long_counts[0],
        large.calls().len() - long_counts[1],
    ];
    eprintln!("regular short: Generate={short_counts:?}");
    assert_eq!(short_counts, [4, 4]);
    assert_eq!(long_counts, [0, 8]);
    assert!(statuses.iter().all(|status| *status == StatusCode::OK));
}

/// Both PD legs independently need room for the input; selection still uses
/// real compatible pairs, and each accepted request reaches each leg once.
#[tokio::test]
#[expect(clippy::print_stderr, reason = "reproducible A/B diagnostics")]
async fn pd_filters_both_context_windows() {
    let dir = tempfile::tempdir().unwrap();
    let ps = Engine::start(dir.path(), "ps", WorkerType::Prefill, Some(16), "a").await;
    let pl = Engine::start(dir.path(), "pl", WorkerType::Prefill, Some(64), "a").await;
    let ds = Engine::start(dir.path(), "ds", WorkerType::Decode, Some(16), "a").await;
    let dl = Engine::start(dir.path(), "dl", WorkerType::Decode, Some(64), "a").await;
    let router = router(dir.path(), &[&ps, &pl, &ds, &dl], true).await;
    let mut statuses = vec![];
    for _ in 0..8 {
        statuses.push(request(router.as_ref(), 24).await.0);
    }
    let counts = [
        ps.calls().len(),
        pl.calls().len(),
        ds.calls().len(),
        dl.calls().len(),
    ];
    eprintln!("PD long: statuses={statuses:?}, Generate[Psmall,Plarge,Dsmall,Dlarge]={counts:?}");
    for _ in 0..8 {
        assert_eq!(request(router.as_ref(), 8).await.0, StatusCode::OK);
    }
    let short_counts = [
        ps.calls().len() - counts[0],
        pl.calls().len() - counts[1],
        ds.calls().len() - counts[2],
        dl.calls().len() - counts[3],
    ];
    eprintln!("PD short: Generate={short_counts:?}");
    assert_eq!(short_counts, [4, 4, 4, 4]);
    assert_eq!(counts, [0, 8, 0, 8]);
    assert!(statuses.iter().all(|status| *status == StatusCode::OK));
}

/// A large node being unhealthy is transient, while every advertised window
/// being too small is a client error. Neither case dispatches to a small node.
#[tokio::test]
async fn capacity_and_availability_are_distinct() {
    for role in [WorkerType::Regular, WorkerType::Prefill, WorkerType::Decode] {
        let pd = role != WorkerType::Regular;
        let dir = tempfile::tempdir().unwrap();
        let small = Engine::start(dir.path(), "small", role, Some(16), "a").await;
        let large = Engine::start(dir.path(), "large", role, Some(64), "a").await;
        let partner_role = if role == WorkerType::Decode {
            WorkerType::Prefill
        } else {
            WorkerType::Decode
        };
        let decode = Engine::start(dir.path(), "partner", partner_role, Some(64), "a").await;
        let engines = if pd {
            vec![&small, &large, &decode]
        } else {
            vec![&small, &large]
        };
        let router = router(dir.path(), &engines, pd).await;
        let (status, body) = request(router.as_ref(), 65).await;
        assert_eq!(status, StatusCode::BAD_REQUEST, "{body}");
        assert_eq!(body["error"]["code"], "context_length_exceeded");
        large.worker.set_status(WorkerStatus::NotReady);
        let (status, body) = request(router.as_ref(), 24).await;
        assert_eq!(status, StatusCode::SERVICE_UNAVAILABLE, "{body}");
        assert!(engines.iter().all(|engine| engine.calls().is_empty()));
    }
}

/// An unknown window stays eligible; it is never treated as zero.
#[tokio::test]
async fn unknown_window_remains_eligible() {
    for role in [WorkerType::Regular, WorkerType::Prefill, WorkerType::Decode] {
        let dir = tempfile::tempdir().unwrap();
        let pd = role != WorkerType::Regular;
        let small = Engine::start(dir.path(), "small", role, Some(16), "a").await;
        let unknown = Engine::start(dir.path(), "unknown", role, None, "a").await;
        let partner_role = if role == WorkerType::Decode {
            WorkerType::Prefill
        } else {
            WorkerType::Decode
        };
        let partner = Engine::start(dir.path(), "partner", partner_role, Some(64), "a").await;
        let engines = if pd {
            vec![&small, &unknown, &partner]
        } else {
            vec![&small, &unknown]
        };
        let router = router(dir.path(), &engines, pd).await;
        for _ in 0..4 {
            assert_eq!(request(router.as_ref(), 24).await.0, StatusCode::OK);
        }
        assert_eq!([small.calls().len(), unknown.calls().len()], [0, 4]);
        if pd {
            assert_eq!(partner.calls().len(), 4);
        }
    }
}

/// Large legs on incompatible protocols cannot be combined into a false fit.
#[tokio::test]
async fn pd_capacity_is_checked_over_compatible_pairs() {
    let dir = tempfile::tempdir().unwrap();
    let pa = Engine::start(dir.path(), "pa", WorkerType::Prefill, Some(64), "a").await;
    let da = Engine::start(dir.path(), "da", WorkerType::Decode, Some(16), "a").await;
    let pb = Engine::start(dir.path(), "pb", WorkerType::Prefill, Some(16), "b").await;
    let db = Engine::start(dir.path(), "db", WorkerType::Decode, Some(64), "b").await;
    let engines = [&pa, &da, &pb, &db];
    let router = router(dir.path(), &engines, true).await;
    let (status, body) = request(router.as_ref(), 24).await;
    assert_eq!(status, StatusCode::BAD_REQUEST, "{body}");
    assert_eq!(body["error"]["code"], "context_length_exceeded");
    assert!(engines.iter().all(|engine| engine.calls().is_empty()));
}

/// Batched completion selection uses its longest item rather than the first
/// prompt's routing proxy; absent and zero output budgets do not erase input.
#[tokio::test]
async fn batch_uses_longest_prompt_with_absent_or_zero_output_budget() {
    let dir = tempfile::tempdir().unwrap();
    let small = Engine::start(dir.path(), "small", WorkerType::Regular, Some(16), "a").await;
    let large = Engine::start(dir.path(), "large", WorkerType::Regular, Some(64), "a").await;
    let router = router(dir.path(), &[&small, &large], false).await;
    for budget in [None, Some(0), Some(1)] {
        let mut body =
            serde_json::json!({"model":MODEL, "prompt":["Hello ".repeat(8), "Hello ".repeat(24)]});
        if let Some(budget) = budget {
            body["max_tokens"] = budget.into();
        }
        let (status, body) = send(router.as_ref(), serde_json::from_value(body).unwrap()).await;
        assert_eq!(status, StatusCode::OK, "{body}");
    }
    assert!(small.calls().is_empty());
    let lengths: Vec<_> = large
        .calls()
        .iter()
        .map(|call| call["input_ids"].as_array().unwrap().len())
        .collect();
    assert_eq!(lengths.len(), 6);
    assert_eq!(lengths.iter().filter(|&&len| len == 24).count(), 3);
    // Ordinary profiles leave input + output admission/clamping to the engine.
    // Each bound fits 64 here, while their sum (80) does not.
    for _ in 0..2 {
        let request = serde_json::from_value(serde_json::json!({
            "model": MODEL, "prompt": "Hello ".repeat(48), "max_tokens": 32,
        }))
        .unwrap();
        let (status, body) = send(router.as_ref(), request).await;
        assert_eq!(status, StatusCode::OK, "{body}");
    }
    assert!(small.calls().is_empty());
    assert_eq!(large.calls().len(), 8);
}
