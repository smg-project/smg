def manifest(name: str, version: str, dependencies: str = "") -> str:
    return (
        f'[package]\nname = "{name}"\nversion = "{version}"\nedition = "2021"\n'
        f'description = "the {name} crate"\n{dependencies}'
    )


def entry(name: str, version: str, registry: bool = False, deps: tuple[str, ...] = ()) -> str:
    """One [[package]] entry of a lock file: a registry dependency carries a source and a checksum,
    a workspace crate neither."""
    text = f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
    if registry:
        text += (
            'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
            f'checksum = "{name}-{version}-checksum"\n'
        )
    if deps:
        text += "dependencies = [\n" + "".join(f' "{dep}",\n' for dep in deps) + "]\n"
    return text + "\n"


def lock(gateway: str = "1.14.0-rc.1", parser: str = "1.10.1", serde: str = "1.0.1") -> str:
    return (
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n"
        + entry("serde", serde, registry=True)
        + entry("smg", gateway, deps=("serde", "tool-parser"))
        + entry("smg-python", gateway, deps=("smg",))
        + entry("tool-parser", parser, deps=("serde",))
    )


