class Tree:
    """A repository with the base tree committed; ``head`` commits a change and names it."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.git("init", "--quiet", "-b", "main")
        for path, text in BASE.items():
            self.put(path, text)
        self.base = self.commit("the base tree")

    def git(self, *args: str) -> str:
        env = {
            "GIT_AUTHOR_NAME": "t",
            "GIT_AUTHOR_EMAIL": "t@example.invalid",
            "GIT_COMMITTER_NAME": "t",
            "GIT_COMMITTER_EMAIL": "t@example.invalid",
            "HOME": str(self.root),
            "PATH": "/usr/bin:/bin",
        }
        done = subprocess.run(
            ["git", *args], cwd=self.root, env=env, check=True, capture_output=True, text=True
        )
        return done.stdout.strip()

    def put(self, path: str, text: str | None) -> None:
        file = self.root / path
        if text is None:
            file.unlink()
            return
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text)

    def commit(self, subject: str) -> str:
        self.git("add", "-A")
        self.git("commit", "--quiet", "-m", subject)
        return self.git("rev-parse", "HEAD")

    def head(self, changes: dict[str, str | None]) -> str:
        """A commit on the base with these files written (None removes one)."""
        self.git("checkout", "--quiet", self.base)
        for path, text in changes.items():
            self.put(path, text)
        return self.commit("the head")


