def test_a_crate_step_with_its_pins_and_lock_entry_is_version_only(mod, crv, tree: Tree) -> None:
    step = {
        "crates/tool_parser/Cargo.toml": manifest("tool-parser", "1.10.2"),
        "Cargo.toml": BASE["Cargo.toml"].replace('version = "1.10.1"', 'version = "1.10.2"'),
        "model_gateway/Cargo.toml": BASE["model_gateway/Cargo.toml"].replace(
            'version = "1.10.1"', 'version = "1.10.2"'
        ),
        "Cargo.lock": lock(parser="1.10.2"),
    }
    done = verdict(mod, crv, tree, tree.head(step))
    assert done.version_only
    assert done.reason == "4 file(s) move nothing but versions: 1.10.1 -> 1.10.2"
    # with the gateway's bump in the same change: two moves
    done = verdict(
        mod,
        crv,
        tree,
        tree.head({**GATEWAY_BUMP, **step, "Cargo.lock": lock("1.14.0-rc.2", "1.10.2")}),
    )
    assert done.version_only
    assert done.reason.endswith(": 1.10.1 -> 1.10.2, 1.14.0-rc.1 -> 1.14.0-rc.2")


