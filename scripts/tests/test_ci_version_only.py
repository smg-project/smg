def test_the_carriers_are_the_checkers_files_the_root_manifest_and_the_lock(mod, crv) -> None:
    kinds = mod.carriers(crv)
    expected = {c.version_file for c in (*crv.CRATES, *crv.PACKAGES)} | {
        m.file for m in crv.MIRRORS
    }
    assert set(kinds) == expected | {"Cargo.toml", "Cargo.lock"}
    assert kinds["Cargo.lock"] == "lock" and kinds["Cargo.toml"] == "workspace"
    assert kinds["deploy/helm/smg/Chart.yaml"] == "helm"
    assert kinds[".github/workflows/release-engine-docker.yml"] == "workflow"
    assert kinds["bindings/python/src/smg/version.py"] == "python"
    assert kinds["bindings/python/pyproject.toml"] == kinds["model_gateway/Cargo.toml"] == "toml"
    assert {"tool-parser", "smg", "smg-data-connector", "data-connector"} <= mod.workspace_keys(crv)


def test_a_version_line_splits_around_its_version(mod) -> None:
    keys = frozenset({"tool-parser"})
    assert mod.version_span("toml", 'version = "1.14.0-rc.1"', keys) == (
        'version = "',
        "1.14.0-rc.1",
        '"',
    )
    assert mod.version_span("python", '__version__ = "1.14.0"\n'.rstrip(), keys) == (
        '__version__ = "',
        "1.14.0",
        '"',
    )
    assert mod.version_span("helm", 'appVersion: "1.14.0"', keys) == (
        'appVersion: "',
        "1.14.0",
        '"',
    )
    assert mod.version_span("helm", "version: 1.14.0", keys) == ("version: ", "1.14.0", "")
    assert mod.version_span("workflow", "  SMG_RELEASE_TAG: v1.14.0", keys) == (
        "  SMG_RELEASE_TAG: v",
        "1.14.0",
        "",
    )
    pin = 'tool-parser = { version = "1.10.1", path = "crates/tool_parser" }'
    assert mod.version_span("workspace", pin, keys) == (
        'tool-parser = { version = "',
        "1.10.1",
        '", path = "crates/tool_parser" }',
    )
    assert mod.version_span("toml", pin, keys) == mod.version_span("workspace", pin, keys)
    # a third-party pin, a name, a description: no version line
    assert mod.version_span("toml", 'serde = { version = "1.0.1" }', keys) is None
    assert mod.version_span("workspace", 'version = "1.14.0"', keys) is None
    assert mod.version_span("toml", 'name = "smg"', keys) is None
    assert mod.version_span("toml", 'description = "the 1.14.0 release"', keys) is None


