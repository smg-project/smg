# --- the command line ---------------------------------------------------------------------


def run(tree: Tree, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), "-C", str(tree.root), *args],
        capture_output=True,
        text=True,
        env={
            **INTERPRETER_ENV,
            "PATH": "/usr/bin:/bin",
            "HOME": str(tree.root),
            "PYTHONDONTWRITEBYTECODE": "1",
        },
    )


def test_the_command_line_exits_0_for_version_only_1_for_not_and_2_when_it_cannot_read(
    tree: Tree,
) -> None:
    bump = tree.head(GATEWAY_BUMP)
    done = run(tree, tree.base, bump)
    assert done.returncode == 0, done.stderr
    assert (
        done.stdout
        == "version-only: 8 file(s) move nothing but versions: 1.14.0-rc.1 -> 1.14.0-rc.2\n"
    )
    # the head defaults to HEAD: the checkout is at the bump
    assert run(tree, tree.base).returncode == 0
    code = tree.head(
        {**GATEWAY_BUMP, "crates/tool_parser/src/lib.rs": "pub fn parse() -> u8 { 1 }\n"}
    )
    done = run(tree, tree.base, code)
    assert done.returncode == 1
    assert done.stdout == "not version-only: crates/tool_parser/src/lib.rs: not a version carrier\n"
    unknown = run(tree, "0000000000000000000000000000000000000001", bump)
    assert unknown.returncode == 2 and unknown.stdout == ""
    assert unknown.stderr.startswith("ci_version_only: fatal:")


