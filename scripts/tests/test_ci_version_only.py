def test_the_lock_alone_moving_the_workspace_crates_is_version_only(mod, crv, tree: Tree) -> None:
    done = verdict(mod, crv, tree, tree.head({"Cargo.lock": lock(gateway="1.14.0-rc.2")}))
    assert done.version_only
    assert done.reason == "1 file(s) move nothing but versions: 1.14.0-rc.1 -> 1.14.0-rc.2"


def test_the_lock_alone_moving_a_dependency_is_not(mod, crv, tree: Tree) -> None:
    done = verdict(mod, crv, tree, tree.head({"Cargo.lock": lock(serde="1.0.2")}))
    assert not done.version_only
    assert done.reason == "Cargo.lock: serde 1.0.1 -> 1.0.2: a dependency moved"
    # an entry added, or the lock's own format version moved
    added = lock() + entry("syn", "2.0.0", registry=True)
    assert verdict(mod, crv, tree, tree.head({"Cargo.lock": added})).reason == (
        "Cargo.lock: the number of entries changed (4 -> 5)"
    )
    bumped_format = lock().replace("version = 4", "version = 5")
    assert verdict(mod, crv, tree, tree.head({"Cargo.lock": bumped_format})).reason == (
        "Cargo.lock: a table other than the packages changed"
    )


