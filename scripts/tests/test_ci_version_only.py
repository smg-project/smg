def test_the_label_is_read_where_the_change_is_classified(workflow) -> None:
    """The classify step yields to ci:full itself, with the lanes step's expression, so the job
    output, the summary line and the lanes agree; the benchmark job reads the output."""
    jobs, steps = workflow
    classify, lanes = steps["version-only"], steps["lanes"]
    assert classify["env"]["FORCE_FULL"] == lanes["env"]["FORCE_FULL"]
    script = classify["run"]
    assert script.index('"$FORCE_FULL" = "true"') < script.index("git fetch")
    assert jobs["detect-changes"]["outputs"]["card-tier-from"] == (
        "${{ steps.version-only.outputs.card-tier-from }}"
    )
    assert "needs.detect-changes.outputs.card-tier-from == ''" in jobs["benchmarks"]["if"]
    assert jobs["detect-changes"]["permissions"]["actions"] == "read"


def run_classify_step(
    script: str, tmp_path: Path, **env: str
) -> tuple[subprocess.CompletedProcess[str], str]:
    """The step's shell with git and gh stubbed to fail loudly: an early return calls neither."""
    stubs = tmp_path / "stubs"
    stubs.mkdir(exist_ok=True)
    for name in ("git", "gh"):
        stub = stubs / name
        stub.write_text('#!/usr/bin/env bash\necho "$(basename "$0") called" >&2\nexit 99\n')
        stub.chmod(0o755)
    output = tmp_path / "output"
    output.write_text("")
    summary = tmp_path / "summary"
    summary.write_text("")
    done = subprocess.run(
        ["bash", "-e", "-c", script],
        capture_output=True,
        text=True,
        env={
            "PATH": f"{stubs}:/usr/bin:/bin",
            "GITHUB_OUTPUT": str(output),
            "GITHUB_STEP_SUMMARY": str(summary),
            "GITHUB_REPOSITORY": "example/repo",
            **env,
        },
    )
    assert summary.read_text() == "", "no summary line without an inherited card tier"
    return done, output.read_text()


def test_the_classify_step_keeps_every_lane_under_the_label_or_without_a_base(
    workflow, tmp_path: Path
) -> None:
    _, steps = workflow
    script = steps["version-only"]["run"]
    labelled, output = run_classify_step(script, tmp_path, FORCE_FULL="true", BASE="a" * 40)
    assert labelled.returncode == 0, labelled.stderr
    assert "the label ci:full: every lane" in labelled.stdout
    assert "called" not in labelled.stderr and output == "card-tier-from=\n"
    for base in ("", "0" * 40, "main"):
        plain, output = run_classify_step(script, tmp_path, FORCE_FULL="false", BASE=base)
        assert plain.returncode == 0, plain.stderr
        assert "no commit to classify against" in plain.stdout, base
        assert "called" not in plain.stderr and output == "card-tier-from=\n", base
    # with a base the fetch comes first, and a fetch that fails keeps every lane
    fetched, output = run_classify_step(script, tmp_path, FORCE_FULL="false", BASE="b" * 40)
    assert fetched.returncode == 0, fetched.stderr
    assert "git called" in fetched.stderr and "gh called" not in fetched.stderr
    assert "cannot fetch" in fetched.stdout and output == "card-tier-from=\n"


def test_the_classify_step_takes_a_passed_run_outside_a_pull_request(workflow) -> None:
    """The run read: the newest passed push or dispatch run of the base. A pull request's run can pass
    with the card lanes skipped (the docs-only shortcut), so it stands for nothing, whatever its place."""
    if shutil.which("jq") is None:
        pytest.skip("the expression is evaluated by jq")
    _, steps = workflow
    expression = re.search(r"--jq '([^']+)'", steps["version-only"]["run"])
    assert expression, "the classify step reads the base's runs with one --jq expression"

    def selected(*runs: tuple[str, str]) -> str:
        page = {
            "workflow_runs": [
                {
                    "conclusion": conclusion,
                    "event": event,
                    "html_url": f"https://example.invalid/runs/{i}",
                }
                for i, (conclusion, event) in enumerate(runs, 1)
            ]
        }
        done = subprocess.run(
            ["jq", "-r", expression.group(1)],
            input=json.dumps(page),
            capture_output=True,
            text=True,
            check=True,
        )
        return done.stdout

    assert selected() == ""
    assert selected(("success", "pull_request")) == ""
    assert selected(("failure", "push"), ("cancelled", "workflow_dispatch")) == ""
    assert (
        selected(
            ("success", "pull_request"),
            ("failure", "push"),
            ("success", "push"),
            ("success", "push"),
        )
        == "https://example.invalid/runs/3\n"
    )
    assert (
        selected(("success", "pull_request"), ("success", "workflow_dispatch"))
        == "https://example.invalid/runs/2\n"
    )


def run_lanes_step(script: str, tmp_path: Path, **env: str) -> dict[str, str]:
    """The lanes step's Python with the given step outputs in its environment: the decisions."""
    assert script.startswith("python3 - <<'EOF'\n")
    body = script[len("python3 - <<'EOF'\n") : script.rstrip().rfind("EOF")]
    output = tmp_path / "lanes-output"
    output.write_text("")
    done = subprocess.run(
        [sys.executable, "-"],
        input=body,
        capture_output=True,
        text=True,
        env={**INTERPRETER_ENV, "PATH": "/usr/bin:/bin", "GITHUB_OUTPUT": str(output), **env},
    )
    assert done.returncode == 0, done.stderr
    return dict(line.split("=", 1) for line in output.read_text().splitlines())


def test_the_lanes_step_skips_the_card_tier_on_an_inherited_change_alone(
    workflow, tmp_path: Path
) -> None:
    _, steps = workflow
    script = steps["lanes"]["run"]
    bump = json.dumps(["Cargo.lock", "model_gateway/Cargo.toml", "deploy/helm/smg/Chart.yaml"])
    on_pull_request = {"CHANGED_FILES": bump, "DOCS": "false", "NON_DOCS": "true", "TESTS": "false"}
    push = run_lanes_step(
        script, tmp_path, PULL_REQUEST="false", FORCE_FULL="false", CARD_TIER_FROM="a" * 40
    )
    assert all(push[f"skip-{area}"] == "true" for area in CARD_AREAS)
    assert push["skip-vendor"] == "false" and push["docs-only"] == "false"
    plain = run_lanes_step(
        script, tmp_path, PULL_REQUEST="false", FORCE_FULL="false", CARD_TIER_FROM=""
    )
    assert all(value == "false" for key, value in plain.items() if key.startswith("skip-"))
    pull = run_lanes_step(
        script,
        tmp_path,
        PULL_REQUEST="true",
        FORCE_FULL="false",
        CARD_TIER_FROM="a" * 40,
        **on_pull_request,
    )
    assert all(pull[f"skip-{area}"] == "true" for area in CARD_AREAS)
